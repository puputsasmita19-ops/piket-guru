/** R114: offline integrity guard tests. No production Firebase, IndexedDB, or network. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const require=createRequire(import.meta.url);
const ts=require('/opt/nvm/versions/node/v22.16.0/lib/node_modules/typescript');
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=file=>readFileSync(path.join(root,file),'utf8');
let count=0;
const check=(condition,label)=>{assert.ok(condition,label);console.log('PASS',label);count++};
const src=read('src/services/offline/syncQueueService.ts');
const state={items:[],fail:false,strict:null};
const storage={getSyncItemsByUser:async(_uid,opt)=>{state.strict=opt?.strict;if(state.fail)throw Error('INDEXEDDB_NOT_AVAILABLE');return state.items},getProjectId:()=> 'school'};
const auth={currentUser:{uid:'guru-a'}};
const compiled=ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const module={exports:{}};
const sandbox={module,exports:module.exports,console:{warn:()=>{},error:()=>{},log:()=>{}},setTimeout,clearTimeout,setInterval,clearInterval,Date,Uint8Array,TextEncoder,crypto:globalThis.crypto,navigator:{onLine:false},fetch:undefined,require:(id)=>{
 if(id.endsWith('offlineStorage'))return {OfflineStorage:storage};
 if(id.endsWith('draftService'))return {DraftService:{}};
 if(id.endsWith('firebaseAuth'))return {auth};
 if(id.endsWith('permissions'))return {PERMISSIONS:{},checkUserPermission:()=>false};
 throw Error('Unexpected import '+id);
}};
vm.runInNewContext(compiled,sandbox,{filename:'syncQueueService.js'});
const svc=module.exports.SyncQueueService;
const seen=[];svc.subscribe(status=>seen.push(status));
state.fail=true;
const failed=await svc.refreshStatus('guru-a');
check(failed.storageError===true,'IndexedDB read error is not represented as known empty queue');
check(failed.pendingCount===0&&failed.items.length===0,'Unknown queue contents are never invented');
check(state.strict===true,'Status read explicitly requires strict durable storage');
check(seen.at(-1)?.storageError===true,'Warning state is broadcast to subscribers');
state.fail=false;
state.items=[{userId:'guru-a',projectId:'school',status:'PENDING_NETWORK'},{userId:'guru-a',projectId:'school',status:'NEEDS_ACTION'}];
const recovered=await svc.refreshStatus('guru-a');
check(recovered.storageError===false&&recovered.pendingCount===1&&recovered.needsActionCount===1,'Recovered store correctly reports unsent and actionable work');
check(seen.at(-1)?.storageError===false,'Restored status clears prior storage warning');
const panel=read('src/components/layout/OfflineSyncPanel.tsx');
const modal=read('src/components/layout/OfflineSyncModal.tsx');
const badge=read('src/components/layout/OfflineSyncBadge.tsx');
check(panel.includes("statusTitle = 'Penyimpanan belum terbaca'")&&modal.includes('Penyimpanan offline belum dapat diperiksa'),'Panel and modal both warn rather than claim success');
check(panel.includes('latest.storageError')&&modal.includes('latest.storageError'),'Sync result is checked after attempted delivery');
check(panel.includes('latest.pendingCount > 0')&&modal.includes('latest.pendingCount > 0'),'Zero processed with pending queue cannot be presented as empty');
check(panel.includes('syncStatus.storageError || isOffline || isOfflineSession')&&modal.includes('syncStatus.storageError || isOffline || isOfflineSession'),'Unverified and storage-error sessions cannot start manual sends');
check(badge.includes("shortLabel = 'Status belum terbaca'"),'Compact badge exposes unknown storage state');
check((panel.match(/await OfflineStorage.clearDisplayCacheOnly\(currentUser.id\)/g)||[]).length===1,'Display cache cleanup runs once and does not duplicate storage work');
check(panel.includes('Data tersimpan belum dapat diperiksa'),'Existing trusted-device warning remains');
check(read('src/hooks/useAutomaticSync.ts').includes('getSyncItemsByUser(user.id, { strict: true })'),'Automatic reconnect never mistakes unreadable storage for empty queue');
console.log(`${count}/${count} R114 integrity assertions PASS`);
